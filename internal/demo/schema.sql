CREATE SCHEMA IF NOT EXISTS demo_shop;

-- Demo only: EXPLAIN of DML requires the corresponding table privileges.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hunter') THEN
        GRANT USAGE ON SCHEMA demo_shop TO hunter;
        ALTER DEFAULT PRIVILEGES IN SCHEMA demo_shop GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hunter;
        ALTER DEFAULT PRIVILEGES IN SCHEMA demo_shop GRANT USAGE ON SEQUENCES TO hunter;
        GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA demo_shop TO hunter;
        GRANT USAGE ON ALL SEQUENCES IN SCHEMA demo_shop TO hunter;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS demo_shop.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS demo_shop.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    price_cents integer NOT NULL CHECK (price_cents > 0)
);
CREATE TABLE IF NOT EXISTS demo_shop.inventory (
    product_id bigint PRIMARY KEY REFERENCES demo_shop.products(id),
    quantity integer NOT NULL CHECK (quantity >= 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS demo_shop.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES demo_shop.customers(id),
    status text NOT NULL CHECK (status IN ('paid', 'pending', 'cancelled')),
    total_cents bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_customer_created ON demo_shop.orders(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_created ON demo_shop.orders(created_at);
CREATE TABLE IF NOT EXISTS demo_shop.order_items (
    order_id bigint NOT NULL REFERENCES demo_shop.orders(id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES demo_shop.products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    price_cents integer NOT NULL,
    PRIMARY KEY (order_id, product_id)
);
CREATE TABLE IF NOT EXISTS demo_shop.payments (
    order_id bigint PRIMARY KEY REFERENCES demo_shop.orders(id) ON DELETE CASCADE,
    amount_cents bigint NOT NULL,
    status text NOT NULL CHECK (status IN ('captured', 'pending')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS demo_shop.seed_versions (version integer PRIMARY KEY);
